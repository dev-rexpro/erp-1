export interface LaunchpadTile {
  id: string
  title: string
  subtitle: string
  groupId: string
  groupName: string
  url: string
  icon: ComponentType<{ className?: string }>
  type: 'kpi' | 'action' | 'chart' | 'shortcut'
  
  // KPI / Data attributes
  kpiValue?: string | number
  kpiUnit?: string
  kpiSubtitle?: string
  kpiTrend?: {
    value: string
    positive?: boolean
  }
  statusBadge?: {
    label: string
    variant?: 'default' | 'outline' | 'secondary' | 'destructive' | 'success' | 'warning'
  }
  
  // Quick Action
  actionLabel?: string
  actionUrl?: string
  
  // Chart / Progress
  progress?: number
  
  // Tagging & Search
  tags: string[]
  isFavoriteDefault?: boolean
}

